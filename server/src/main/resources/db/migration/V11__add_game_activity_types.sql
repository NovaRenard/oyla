-- Stage 5: child games (ODD_ONE, REMEMBER, MEMORY, SORT, WORD_BUILD, MAZE) are regular content
-- activities and regular session exercises. session_exercises.activity_type has no CHECK constraint.
ALTER TABLE content_exercises DROP CONSTRAINT IF EXISTS chk_content_exercises_type;
ALTER TABLE content_exercises ADD CONSTRAINT chk_content_exercises_type
    CHECK (activity_type IN ('SINGLE_CHOICE', 'WHITEBOARD', 'ODD_ONE', 'REMEMBER', 'MEMORY', 'SORT', 'WORD_BUILD', 'MAZE'));

-- Type-specific game settings (group labels, show time, maze layout, word picture).
ALTER TABLE content_exercises ADD COLUMN game_config JSONB;

-- SORT group ("A"/"B") and WORD_BUILD letter order (1..n, NULL for distractor letters).
ALTER TABLE content_exercise_options ADD COLUMN group_key VARCHAR(8), ADD COLUMN sequence_index INTEGER;
ALTER TABLE content_exercise_options ADD CONSTRAINT chk_content_exercise_options_group
    CHECK (group_key IS NULL OR group_key IN ('A', 'B'));
ALTER TABLE content_exercise_options ADD CONSTRAINT chk_content_exercise_options_sequence
    CHECK (sequence_index IS NULL OR sequence_index BETWEEN 1 AND 10);
-- WORD_BUILD allows up to 10 tiles (REMEMBER 9, MEMORY/SORT 8).
ALTER TABLE content_exercise_options DROP CONSTRAINT IF EXISTS chk_content_exercise_options_position;
ALTER TABLE content_exercise_options ADD CONSTRAINT chk_content_exercise_options_position CHECK (sort_order BETWEEN 1 AND 10);

-- MEMORY: second card option id; SORT: target group.
ALTER TABLE attempts ADD COLUMN secondary_value VARCHAR(120);

